#!/usr/bin/env python3
"""Copy nfl_model.py into the single Colab cell of notebooks/NFL_C_B_MODEL.ipynb.

The notebook is the Colab entry point (paste-and-run, Google Drive storage);
nfl_model.py is the source of truth. tests/test_notebook_sync.py fails if the
two drift, so run this after every model edit:

    python sync_notebook.py
"""
import json
import sys
from pathlib import Path

MODEL = Path("nfl_model.py")
COLLECTOR = Path("availability_collect.py")
REPLACEMENT = Path("qb_replacement.py")
NOTEBOOK = Path("notebooks/NFL_C_B_MODEL.ipynb")


def source(model=MODEL):
    """One self-contained Colab cell, including the collector from the same checkout."""
    model=Path(model)
    collector=(model.parent/COLLECTOR).read_text(encoding='utf-8')
    prelude=("# Generated by sync_notebook.py; collector and model have the same source revision.\n"
             "import sys as _nfl_sys, types as _nfl_types\n"
             "_nfl_collector = _nfl_types.ModuleType('availability_collect')\n"
             "_nfl_sys.modules['availability_collect'] = _nfl_collector\n"
             f"exec(compile({collector!r}, 'availability_collect.py', 'exec'), _nfl_collector.__dict__)\n"
             "del _nfl_collector, _nfl_types, _nfl_sys\n\n")
    replacement=(model.parent/REPLACEMENT).read_text(encoding='utf-8')
    extra=("import sys as _qr_sys, types as _qr_types\n"
           "_qr_module = _qr_types.ModuleType('qb_replacement')\n"
           "_qr_sys.modules['qb_replacement'] = _qr_module\n"
           f"exec(compile({replacement!r}, 'qb_replacement.py', 'exec'), _qr_module.__dict__)\n"
           "del _qr_module, _qr_types, _qr_sys\n\n")
    return prelude+extra+model.read_text(encoding='utf-8')


def sync(model=MODEL, notebook=NOTEBOOK):
    """Rewrite the notebook cell from the module; return True if it changed."""
    nb = json.loads(Path(notebook).read_text(encoding="utf-8"))
    cell = nb["cells"][0]
    src = source(model)
    new = src.splitlines(keepends=True)
    changed = cell["source"] != new or cell.get("outputs") or cell.get("execution_count") is not None
    if changed:
        cell["source"], cell["outputs"], cell["execution_count"] = new, [], None
        Path(notebook).write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return bool(changed)


if __name__ == "__main__":
    print("notebook updated" if sync() else "notebook already in sync")
    sys.exit(0)
